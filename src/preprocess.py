"""
Предобработка текста перед подачей в модель.

Что делаем и зачем:
1. Приводим к нижнему регистру — иначе "Отлично" и "отлично" модель
   считает разными словами.
2. Убираем пунктуацию и цифры — они почти не несут смысла для тональности.
3. Убираем лишние пробелы.

Это самый базовый вариант. Позже можно добавить:
- удаление стоп-слов (предлоги, союзы — "и", "но", "в")
- лемматизацию (приведение слов к начальной форме: "покупал" -> "покупать")
  например через библиотеку pymorphy2
"""

import re


def clean_text(text: str) -> str:
    """Чистит один текст: нижний регистр, без пунктуации и цифр."""
    text = text.lower()
    text = re.sub(r"[^а-яёa-z\s]", " ", text)  # оставляем только буквы
    text = re.sub(r"\s+", " ", text).strip()   # убираем лишние пробелы
    return text


def clean_texts(texts: list[str]) -> list[str]:
    """Чистит список текстов (удобно применять к целому столбцу датасета)."""
    return [clean_text(t) for t in texts]


if __name__ == "__main__":
    # Быстрая проверка на живом примере
    example = "Отличный Товар!!! Пришёл за 2 дня, всё СУПЕР :)"
    print("До:  ", example)
    print("После:", clean_text(example))
